const createProductImage = (background, primary, secondary, tertiary = '#111827') => {
  const svg = `
    <svg xmlns="http://www.w3.org/2000/svg" width="900" height="1000" viewBox="0 0 900 1000">
      <rect width="100%" height="100%" fill="${background}" />
      <rect x="140" y="140" width="620" height="720" rx="44" fill="${primary}" />
      <rect x="220" y="220" width="460" height="210" rx="24" fill="${secondary}" />
      <rect x="220" y="470" width="200" height="220" rx="24" fill="${tertiary}" />
      <rect x="470" y="470" width="210" height="220" rx="24" fill="${secondary}" />
    </svg>
  `

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`
}

const createProductVariant = (config) => {
  const baseImages = [
    createProductImage(config.background, config.primary, config.secondary, config.tertiary),
    createProductImage(config.backgroundAlt, config.primaryAlt, config.secondaryAlt, config.tertiaryAlt),
    createProductImage(config.backgroundAlt2, config.primaryAlt2, config.secondaryAlt2, config.tertiaryAlt2),
  ]

  return {
    ...config,
    images: baseImages.map((src, index) => ({
      id: index + 1,
      label: `${config.name} view ${index + 1}`,
      src,
    })),
  }
}

const slugify = (value) =>
  value
